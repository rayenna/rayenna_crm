describe('buildCommercialsWaterfall', () => {
  it('builds payable, subsidy effective, and words', () => {
    const w = buildCommercialsWaterfall(baseProposal());
    expect(w).not.toBeNull();
    expect(w!.preGst).toBe(331000);
    expect(w!.gstAmount).toBe(20850);
    expect(w!.payableToRayenna).toBe(351850);
    expect(w!.effectiveAfterSubsidy).toBe(273850);
    expect(w!.payableInWords).toMatch(/^Rupees /);
    expect(w!.showSubsidy).toBe(true);
  });
});

describe('buildTechDetailCards', () => {
  it('derives module and inverter cards from BOM', () => {
    const cards = buildTechDetailCards(baseProposal());
    expect(cards.map((c) => c.id)).toEqual(['modules', 'inverter']);
    expect(cards[0].manufacturer).toContain('EMMVEE');
    expect(cards[1].manufacturer).toContain('SOLIS');
  });

  it('prefers slash manufacturer lists from BOQ notes and uses the balance as specification', () => {
    const cards = buildTechDetailCards(baseProposal(), null, {
      'pv-modules':
        'NDCR ADANI/EMMVEE/WAAREE 580-600 DCR TOPCON MODULE - 34 NOS',
      inverters: 'HYBRID 20KW 3PH 48V INVERTER (DEYE/POLYCAB/SOLAIRE) - 1 NO',
    });
    const modules = cards.find((c) => c.id === 'modules')!;
    const inverter = cards.find((c) => c.id === 'inverter')!;
    expect(modules.manufacturer).toBe('ADANI/EMMVEE/WAAREE');
    expect(modules.specification).toMatch(/NDCR/);
    expect(modules.specification).toMatch(/580-600/);
    expect(modules.specification).not.toMatch(/ADANI/);
    expect(inverter.manufacturer).toBe('DEYE/POLYCAB/SOLAIRE');
    expect(inverter.specification).toMatch(/HYBRID 20KW/);
    expect(inverter.specification).not.toMatch(/DEYE/);
  });

  it('parses MAKE: slash brands from BOM row specifications when notes are empty', () => {
    const cards = buildTechDetailCards(
      baseProposal({
        bom: [
          {
            category: 'inverters',
            itemName: 'String Inverter',
            specification: 'SOLAR GRID TIED STRING INVERTER-5KW 1PH MAKE:DEYE/GROWATT',
            quantity: '1',
            brand: '',
            isAutoGenerated: true,
          },
        ],
        panelBrand: undefined,
        inverterBrand: undefined,
      }),
    );
    const inverter = cards.find((c) => c.id === 'inverter')!;
    expect(inverter.manufacturer).toBe('DEYE/GROWATT');
    expect(inverter.specification).toMatch(/SOLAR GRID TIED/);
    expect(inverter.specification).not.toMatch(/MAKE/i);
  });
});

describe('parseNoteManufacturerAndSpec', () => {
  it('splits module note brands from the balance', () => {
    const r = parseNoteManufacturerAndSpec(
      'ADANI/EMMVEE/WAREE 600-620 DCR TOPCON MODULE',
    );
    expect(r.manufacturer).toBe('ADANI/EMMVEE/WAREE');
    expect(r.specification).toBe('600-620 DCR TOPCON MODULE');
  });
});

describe('resolveRaciRows', () => {
  it('honours raci-count and toggles from overrides', () => {
    const rows = resolveRaciRows({
      'raci-count': '2',
      'raci-0-desc': 'Custom A',
      'raci-0-rayenna': 'yes',
      'raci-0-client': 'no',
      'raci-1-desc': 'Custom B',
      'raci-1-rayenna': 'no',
      'raci-1-client': 'yes',
    });
    expect(rows).toHaveLength(2);
    expect(rows[0]).toEqual({
      description: 'Custom A',
      rayenna: true,
      client: false,
    });
    expect(rows[1]).toEqual({
      description: 'Custom B',
      rayenna: false,
      client: true,
    });
  });
});

describe('seedAuthorityFees', () => {
  it('scales registration by kW', () => {
    const fees = seedAuthorityFees(5);
    const reg = fees.find((f) => f.id === 'registration');
    expect(reg?.amount).toBe(5000);
  });
});
