import { describe, expect, it } from 'vitest';
import * as docx from 'docx';
import { buildDocx } from './exportDocx';
import {
  buildTechDetailCards,
  parseNoteManufacturerAndSpec,
  resolveRaciRows,
} from './proposalContent';
import {
  OPTIONAL_PROPOSAL_SECTION_IDS,
  isOptionalSectionIncluded,
  normalizeIncludedOptionalSections,
} from './optionalSections';
import type { ProposalData } from './types';

